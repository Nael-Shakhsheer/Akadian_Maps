"""Export the public app + published maps as a static site (GitHub Pages, any static host, a USB stick).

    python tools/export_static.py            # writes docs/ (GitHub Pages: Settings -> Pages -> main, /docs)
    python tools/export_static.py --out dist

Everything the public app does runs in the browser (search, indoor + outdoor routing, 3D views, GPS, parking,
saved places), so the static copy works the same as the engine's public server. Only *published* maps are copied:
the same files the public server already serves to anyone. Schematics, plan renders, OCR and the vault are never
touched. The admin studio is not part of the export.
"""
import argparse, gzip, json, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--home", default=str(ROOT / "engine_data"), help="engine home (reads only published/)")
    ap.add_argument("--out", default=str(ROOT / "docs"))
    a = ap.parse_args()
    pub = Path(a.home) / "published"
    out = Path(a.out)
    if not (pub / "campus").exists():
        sys.exit("Nothing published yet. Run:  python tools/seed_gmu.py --publish-only")
    if out.resolve() in (ROOT.resolve(), APP.resolve(), pub.resolve()) or ROOT.resolve() not in out.resolve().parents:
        sys.exit(f"Refusing to export into {out}: pick a new folder inside the project, like docs/ or dist/.")
    if out.exists():
        if any(out.iterdir()) and not (out / ".akadian-export").exists():
            sys.exit(f"{out} exists and isn't a previous export; not overwriting it.")
        # delete the old files but keep folders: synced folders (OneDrive) lock them, and empty ones are harmless
        for p in sorted(out.rglob("*"), reverse=True):
            if p.is_file() and p.name != ".akadian-export":  # the marker goes last, so a failed run can retry
                p.unlink()

    shutil.copytree(APP, out, dirs_exist_ok=True)
    (out / ".akadian-export").write_text("Generated by tools/export_static.py. Re-run it instead of editing.\n")
    (out / ".nojekyll").write_text("")  # serve files as-is (no Jekyll processing)
    # the engine injects the data location at request time; a static site gets it baked in
    html = (out / "index.html").read_text(encoding="utf-8")
    (out / "index.html").write_text(html.replace("<head>", "<head>\n  <script>window.AKADIAN_DATA = 'data';</script>", 1),
                                    encoding="utf-8")

    data = out / "data"
    n = {"campus": 0, "buildings": 0, "tiles": 0, "fonts": 0}
    for kind in ("campus", "buildings"):
        for f in sorted((pub / kind).glob("*.json")):
            (data / kind).mkdir(parents=True, exist_ok=True)
            json.dump(json.loads(f.read_text(encoding="utf-8")), (data / kind / f.name).open("w", encoding="utf-8"),
                      separators=(",", ":"))
            n[kind] += 1
    # tiles and fonts are stored gzipped; static hosts can't send them with Content-Encoding, so unpack them
    for kind in ("tiles", "fonts"):
        for f in sorted((pub / kind).rglob("*.pbf")):
            raw = f.read_bytes()
            dest = data / kind / f.relative_to(pub / kind)
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(gzip.decompress(raw) if raw[:2] == b"\x1f\x8b" else raw)
            n[kind] += 1
    size = sum(p.stat().st_size for p in out.rglob("*") if p.is_file()) / 1e6
    print(f"Exported to {out}: {n['campus']} campus, {n['buildings']} buildings, {n['tiles']} tiles, "
          f"{n['fonts']} font files ({size:.1f} MB)")


if __name__ == "__main__":
    main()
